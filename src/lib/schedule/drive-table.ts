export function tableDrive(a: string, b: string): { miles: number; minutes: number; ferry: boolean } | null {
  const t = DRIVE_TABLE[a <= b ? `${a}|${b}` : `${b}|${a}`];
  return t ? { miles: t[0], minutes: t[1], ferry: t[2] === 1 } : null;
}

/** The measured numbers for a pair, only while both stores still have the address they were measured at. */
export function tableFor(stores: Pick<Store, "code" | "address">[], a: string, b: string): { miles: number; minutes: number; ferry: boolean } | null {
  const same = (c: string) => {
    const now = stores.find((x) => x.code === c);
    const was = HI_SCHOOL_STORES.find((x) => x.code === c);
    return Boolean(now && was && now.address === was.address);
  };
  return same(a) && same(b) ? tableDrive(a, b) : null;
}
